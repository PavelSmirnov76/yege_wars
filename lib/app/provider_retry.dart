/// Автоповтор упавших провайдеров выключен.
///
/// Riverpod по умолчанию повторяет упавший провайдер до 10 раз, около 40 с,
/// и всё это время экран показывает индикатор загрузки. Без повторов сбой
/// загрузки экрана или списка сразу даёт сообщение и «Повторить».
///
/// Передаётся в `retry` каждого `ProviderScope` приложения — в `main.dart`
/// и в тестах: настройка одна, а не копии.
///
/// Реализует UC-31, UC-34, UC-35, UC-36 и UC-37.
Duration? noProviderRetry(int retryCount, Object error) => null;
