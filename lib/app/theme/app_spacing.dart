/// Токены отступов. Шкала кратна 4 (с малым шагом 2 для тонких случаев).
///
/// Используются вместо числовых литералов в отступах и промежутках:
/// «много воздуха» достигается крупными значениями [xl]–[xxxl].
abstract final class AppSpacing {
  /// 2 — минимальный зазор (например, между иконкой и бейджем).
  static const double xxs = 2;

  /// 4 — зазор внутри плотных элементов.
  static const double xs = 4;

  /// 8 — базовый мелкий отступ.
  static const double sm = 8;

  /// 12 — внутренние отступы компактных контролов.
  static const double md = 12;

  /// 16 — стандартный внутренний отступ карточек и полей.
  static const double lg = 16;

  /// 24 — промежутки между блоками контента.
  static const double xl = 24;

  /// 32 — крупные промежутки между секциями.
  static const double xxl = 32;

  /// 48 — поля страниц и «воздух» вокруг главных блоков.
  static const double xxxl = 48;
}
